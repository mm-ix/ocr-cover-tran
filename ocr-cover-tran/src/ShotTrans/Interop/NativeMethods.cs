    public static Rectangle GetVirtualScreen()
    {
        int x = GetSystemMetrics(SM_XVIRTUALSCREEN);
        int y = GetSystemMetrics(SM_YVIRTUALSCREEN);
        int w = GetSystemMetrics(SM_CXVIRTUALSCREEN);
        int h = GetSystemMetrics(SM_CYVIRTUALSCREEN);
        if (w <= 0 || h <= 0)
        {
            var b = System.Windows.Forms.SystemInformation.VirtualScreen;
            return b;
        }
        return new Rectangle(x, y, w, h);
    }

    public static Rectangle GetMonitorWorkArea(Point pt)
    {
        var handle = MonitorFromPoint(new POINT(pt.X, pt.Y), MONITOR_DEFAULTTONEAREST);
        if (handle != IntPtr.Zero)
        {
            var mi = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
            if (GetMonitorInfo(handle, ref mi))
                return mi.rcWork.ToRectangle();
        }
        return System.Windows.Forms.Screen.FromPoint(pt).WorkingArea;
    }

    /// <summary>返回该点所在显示器的有效 DPI 缩放（96 DPI = 1.0）；失败时回退 1.0。</summary>
    public static float GetDpiScale(Point pt)
    {
        try
        {
            var handle = MonitorFromPoint(new POINT(pt.X, pt.Y), MONITOR_DEFAULTTONEAREST);
            if (handle != IntPtr.Zero &&
                GetDpiForMonitor(handle, MDT_EFFECTIVE_DPI, out uint dpiX, out _) == 0 &&
                dpiX > 0)
            {
                return dpiX / 96f;
            }
        }
        catch
        {
            // shcore.dll 不可用（极旧系统）时按 100% 处理
        }
        return 1f;
    }

